-- Lock the app's RPC functions to the service_role (Supabase secret key).
-- Run only AFTER the app's SUPABASE_KEY is the secret key (sb_secret_...),
-- otherwise the live app loses database access.
do $$
declare f record;
begin
  for f in
    select p.oid::regprocedure as sig
    from pg_proc p join pg_namespace n on n.oid = p.pronamespace
    where n.nspname = 'public' and p.proname like 'ea\_%'
  loop
    execute format('revoke execute on function %s from public, anon, authenticated', f.sig);
    execute format('grant execute on function %s to service_role', f.sig);
  end loop;
end $$;
